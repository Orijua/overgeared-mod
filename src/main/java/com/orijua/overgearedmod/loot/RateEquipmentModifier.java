package com.orijua.overgearedmod.loot;

import com.mojang.serialization.Codec;
import com.mojang.serialization.MapCodec;
import com.mojang.serialization.codecs.RecordCodecBuilder;
import com.orijua.overgearedmod.equipment.EquipmentService;
import com.orijua.overgearedmod.equipment.ItemRating;
import it.unimi.dsi.fastutil.objects.ObjectArrayList;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.level.storage.loot.LootContext;
import net.minecraft.world.level.storage.loot.predicates.LootItemCondition;
import net.neoforged.neoforge.common.loot.IGlobalLootModifier;
import net.neoforged.neoforge.common.loot.LootModifier;

/**
 * Global loot modifier: rates every weapon and armor piece generated by loot tables whose path starts
 * with {@code table_prefix} (any namespace), e.g. {@code "chests/"} for every vanilla and modded chest.
 * Lets existing loot tables give rated gear without copying and editing them.
 */
public final class RateEquipmentModifier extends LootModifier {
    public static final MapCodec<RateEquipmentModifier> CODEC = RecordCodecBuilder.mapCodec(instance -> codecStart(instance).and(instance.group(
            Codec.STRING.fieldOf("table_prefix").forGetter(m -> m.tablePrefix),
            Codec.intRange(0, 1000).optionalFieldOf("luck", 0).forGetter(m -> m.luck),
            ItemRating.CODEC.optionalFieldOf("min_rating", ItemRating.NORMAL).forGetter(m -> m.minimum)
    )).apply(instance, RateEquipmentModifier::new));

    private final String tablePrefix;
    private final int luck;
    private final ItemRating minimum;

    public RateEquipmentModifier(LootItemCondition[] conditions, String tablePrefix, int luck, ItemRating minimum) {
        super(conditions);
        this.tablePrefix = tablePrefix;
        this.luck = luck;
        this.minimum = minimum;
    }

    @Override
    protected ObjectArrayList<ItemStack> doApply(ObjectArrayList<ItemStack> generatedLoot, LootContext context) {
        if (context.getQueriedLootTableId().getPath().startsWith(tablePrefix)) {
            for (ItemStack stack : generatedLoot) {
                EquipmentService.rateLoot(context.getLevel(), stack, luck, minimum, context.getRandom());
            }
        }
        return generatedLoot;
    }

    @Override
    public MapCodec<? extends IGlobalLootModifier> codec() {
        return CODEC;
    }
}
