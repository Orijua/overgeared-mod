    /** Where a piece of a placed Winston lies in the world: its template's origin and rotation. */
    public record PlacedPiece(BlockPos origin, Rotation rotation) {
        /** The world position of the template position (x, y, z) of this piece. */
        public BlockPos at(int x, int y, int z) {
            return StructureTemplate.calculateRelativePosition(settings(), new BlockPos(x, y, z)).offset(origin);
        }

        /** Places {@code template} exactly over this piece (same origin and rotation), without its entities. */
        public boolean place(ServerLevel level, String template) {
            Optional<StructureTemplate> found = level.getStructureManager().get(Overgearedmod.id(template));
            return found.isPresent() && found.get().placeInWorld(level, origin, origin, settings().setIgnoreEntities(true), level.random,
                    Block.UPDATE_ALL);
        }

        private StructurePlaceSettings settings() {
            return new StructurePlaceSettings().setRotation(rotation);
        }
    }

    /** The Winston whose area holds {@code pos}, if any (invalid otherwise). */
    public static StructureStart at(ServerLevel level, BlockPos pos) {
        Structure winston = level.registryAccess().registryOrThrow(Registries.STRUCTURE).get(KEY);
        return winston == null ? StructureStart.INVALID_START : level.structureManager().getStructureAt(pos, winston);
    }

    /** The piece of {@code start} built from {@code template} (a path such as {@link #SQUARE}), if it has one. */
    public static Optional<PlacedPiece> piece(StructureStart start, String template) {
        // A single pool element prints as "Single[Left[<template id>]]".
        String name = "[" + Overgearedmod.MODID + ":" + template + "]";
        return start.getPieces().stream()
                .filter(piece -> piece instanceof PoolElementStructurePiece pool && pool.getElement().toString().contains(name))
                .map(piece -> (PoolElementStructurePiece) piece)
                .map(pool -> new PlacedPiece(pool.getPosition(), pool.getRotation()))
                .findFirst();
    }

